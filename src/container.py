"""Pipeline output container generator.

Produces flat output files in the pipeline output directory:

    outputs/{run_name}/
    ├── {platform}.h5ad              (existing)
    ├── {platform}_transcripts.parquet (existing)
    ├── metadata.json                (merged pipeline metadata)
    ├── cells.parquet                (cell-level visualisation data)
    └── report.html                  (generated by html_report.py)

No subdirectories; no information duplication with the old
``*_report.json`` — *metadata.json* is the single source of truth.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import TYPE_CHECKING

import pandas as pd

if TYPE_CHECKING:
    import anndata

logger = logging.getLogger(__name__)


def _resolve_obs_column(obs: pd.DataFrame, candidates: list[str]) -> str | None:
    for col in candidates:
        if col in obs.columns:
            return col
    return None


def generate_container(
    adata: "anndata.AnnData",
    report_json: dict,
    output_dir: str | Path,
) -> Path:
    """Generate flat container files in *output_dir*.

    Writes ``metadata.json`` and ``cells.parquet`` directly into the
    output directory (no ``container/`` subdirectory).

    Parameters
    ----------
    adata : anndata.AnnData
        AnnData from the completed pipeline.
    report_json : dict
        Pipeline report payload (from ``*_report.json``).
    output_dir : str or Path
        Pipeline output directory.

    Returns
    -------
    Path
        Path to the metadata.json file.
    """
    output_dir = Path(output_dir)

    # ── Build & write metadata.json ──
    metadata = _build_metadata(adata, report_json, output_dir)
    meta_path = output_dir / "metadata.json"
    meta_path.write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2, default=str),
        encoding="utf-8",
    )
    logger.info("Wrote %s", meta_path)

    # ── Build & write cells.parquet ──
    cells_df = _build_cells_dataframe(adata)
    cells_path = output_dir / "cells.parquet"
    cells_df.to_parquet(cells_path, index=False)
    logger.info("Wrote %s  (%d rows, %d columns)", cells_path, len(cells_df), len(cells_df.columns))

    return meta_path


def _build_metadata(
    adata: "anndata.AnnData",
    report_json: dict,
    output_dir: Path,
) -> dict:
    clusters_dist: dict[str, int] = {}
    cluster_col = _resolve_obs_column(adata.obs, ["cluster", "leiden"])
    if cluster_col is not None:
        clusters_dist = _safe_dist(adata.obs[cluster_col])
    else:
        logger.warning("No 'cluster'/'leiden' column — clusters empty.")

    cell_types_dist: dict[str, int] = {}
    ct_col = _resolve_obs_column(adata.obs, ["cell_type", "annotation"])
    if ct_col is not None:
        cell_types_dist = _safe_dist(adata.obs[ct_col])
    else:
        logger.warning("No 'cell_type'/'annotation' column — cell_types empty.")

    spatial_domains_dist: dict[str, int] = {}
    sd_col = _resolve_obs_column(adata.obs, ["spatial_domain", "domain"])
    if sd_col is not None:
        spatial_domains_dist = _safe_dist(adata.obs[sd_col])
    else:
        logger.warning("No 'spatial_domain'/'domain' column — spatial_domains empty.")

    return {
        "run_name": report_json.get("pipeline_name", "unknown"),
        "platform": report_json.get("platform", "unknown"),
        "pipeline_version": report_json.get("pipeline_version", "0.1.0"),
        "source_path": report_json.get("source_path", str(output_dir)),
        "summary": report_json.get("summary", {}),
        "qc_metrics": report_json.get("qc_metrics", {}),
        "step_summary": report_json.get("step_summary", {}),
        "layer_evaluation": report_json.get("layer_evaluation", {}),
        "clusters": {str(k): int(v) for k, v in clusters_dist.items()},
        "cell_types": {str(k): int(v) for k, v in cell_types_dist.items()},
        "spatial_domains": {str(k): int(v) for k, v in spatial_domains_dist.items()},
        "step_order": report_json.get("step_order", []),
        "outputs": report_json.get("outputs", {}),
        "n_obs": report_json.get("n_obs", int(adata.n_obs)),
        "n_vars": report_json.get("n_vars", int(adata.n_vars)),
    }


def _safe_dist(series: pd.Series) -> dict[str, int]:
    return {str(k): int(v) for k, v in series.astype(str).value_counts().sort_index().items()}


def _build_cells_dataframe(adata: "anndata.AnnData") -> pd.DataFrame:
    obs = adata.obs
    n = adata.n_obs
    records: dict[str, list] = {}

    records["cell_id"] = list(adata.obs_names.astype(str))

    cc = _resolve_obs_column(obs, ["cluster", "leiden"])
    records["cluster"] = obs[cc].astype(str).tolist() if cc is not None else [""] * n

    ct = _resolve_obs_column(obs, ["cell_type", "annotation"])
    records["cell_type"] = obs[ct].astype(str).tolist() if ct is not None else [""] * n

    sd = _resolve_obs_column(obs, ["spatial_domain", "domain"])
    records["spatial_domain"] = obs[sd].astype(str).tolist() if sd is not None else [""] * n

    umap = adata.obsm.get("X_umap")
    records["umap_x"] = umap[:, 0].tolist() if umap is not None else [0.0] * n
    records["umap_y"] = umap[:, 1].tolist() if umap is not None else [0.0] * n

    spatial = adata.obsm.get("spatial")
    if spatial is not None:
        records["spatial_x"] = spatial[:, 0].tolist()
        records["spatial_y"] = spatial[:, 1].tolist()
    elif "spatial_x" in obs.columns and "spatial_y" in obs.columns:
        records["spatial_x"] = obs["spatial_x"].astype(float).tolist()
        records["spatial_y"] = obs["spatial_y"].astype(float).tolist()
    else:
        records["spatial_x"] = [0.0] * n
        records["spatial_y"] = [0.0] * n

    records["n_genes"] = obs["n_genes_by_counts"].astype(int).tolist() if "n_genes_by_counts" in obs.columns else [0] * n
    records["n_counts"] = obs["total_counts"].astype(int).tolist() if "total_counts" in obs.columns else [0] * n

    return pd.DataFrame(records)
