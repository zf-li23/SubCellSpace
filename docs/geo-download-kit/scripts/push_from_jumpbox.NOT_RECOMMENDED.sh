#!/bin/bash
# ============================================================================
# ⛔ 反例，不要用 —— 在【跳板机】上 push 到集群
# ----------------------------------------------------------------------------
# 这是 2026-06 初版的做法，后来废弃。保留在这里是为了说明为什么不该这么做：
#
#   1. 进度/超时/断点由跳板机侧的 SSH 会话决定 —— 会话一断，整批作废；
#   2. 跳板机 sshd 通常限制并发与连接数，多开 scp 会被 reset；
#   3. 数据要经过跳板机的出口，和其他人抢带宽；
#   4. 出问题时日志在跳板机上，排查要来回跳。
#
# 正确做法：在集群上运行 pull_from_jumpbox.sh（集群侧发起、rsync 续传、
# 先查源大小再决定是否传输）。
#
# 本文件不参与任何流程，仅作教学用途。
# ============================================================================
set -e

SRC_DIR="${1:?这里原本是跳板机上的下载目录}"
DST="${CLUSTER_USER}@${CLUSTER_HOST}"     # 原脚本里写死的内网 IP
DST_DIR="${DATA_ROOT}/tars_master"

echo "[反例] 在跳板机上 push："
echo "  scp \$SRC_DIR/GSE*_RAW.tar ${DST}:${DST_DIR}/"
echo
echo "症状（当年真实遇到过）："
echo "  · 单个 GSE 传到一半 SSH 掉线 → 目标端留下半个文件，下次仍要重传"
echo "  · 同时开 3 个 scp → 跳板机地址被临时限流，报 Connection reset"
echo "  · 失败后没有任何断点记录，只能靠人工比对大小"
exit 0
